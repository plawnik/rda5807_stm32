#!/usr/bin/env python3
"""Compile the designer export into const flash data; no JSON parser on the MCU.

Bindings below attach the project's natural-language fields to radio functions.
Unknown fields fail the build instead of silently producing an inert menu item.
"""

import argparse
import json
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/menu/radio-menu.json"
HEADER = ROOT / "f103radio/Core/Inc/lcd_layout.h"
OUTPUT = ROOT / "f103radio/Core/Src/lcd_layout.c"

REGIONS = {
    "Siła sygnału FM": "SIGNAL", "RDS status": "RDS",
    "Poziom głośności": "VOLUME", "Bass boost": "BASS",
    "Mono/stereo": "STEREO", "Zegar": "CLOCK",
    "Nazwa zapisanej stacji": "STATION_NAME", "Częstotliwość": "FREQUENCY",
    "Signal_logo": "SIGNAL_ICON", "Ikona glosnika": "SPEAKER",
    "Logo": "LOGO", "Siła sygnału": "RSSI_NUMBER",
    "Poziom glosnosci": "VOLUME_NUMBER", "Tryb_przełączania": "CONTROL",
    "Nazwa stacji PS": "PS", "Rodzaj programu PTY": "PTY",
    "Radio text": "RT", "Radio tekst plus": "RT_SCROLL",
}
ITEMS = {
    "Częstotliwość": ("FREQUENCY", "frequency_khz"),
    "Zakres rozszerzony": ("EXTENDED_RANGE", "extended_tuning"),
    "Seek w górę": ("SEEK_UP", None), "Seek w dół": ("SEEK_DOWN", None),
    "Głośność": ("VOLUME", "volume"), "Wyciszenie": ("MUTE", "muted"),
    "Tryb kanałów": ("AUDIO_MODE", "force_mono"),
    "Bass Boost": ("BASS", "bass_boost"),
    "Próg seek": ("SEEK_THRESHOLD", "seek_threshold"),
    "Uśrednianie RSSI": ("RSSI_AVERAGE", "rssi_average_ms"),
    "AFC": ("AFC", "afc_enabled"), "Dekoder RDS": ("RDS", "rds_enabled"),
    "Standard": ("RBDS", "rbds_enabled"),
    "Ruch enkodera": ("ENCODER_ACTION", "encoder_action"),
    "Przyciski L/P": ("BUTTON_ACTION", "buttons_action"),
    "Kontrast": ("LCD_CONTRAST", "lcd_contrast"),
    "Negatyw": ("LCD_INVERT", "lcd_inverted"),
    "Podświetlenie": ("LCD_BACKLIGHT", "lcd_backlight"),
    "Dodaj stację": ("ADD_STATION", None),
    "Zarządzaj listą": ("STATION_LIST", None),
    "Wersja firmware": ("FIRMWARE_VERSION", None),
    "Ustawienia domyślne": ("DEFAULTS", None),
}
TYPES = {name: "LCD_ENTRY_" + name.upper().replace("-", "_") for name in
         ("number", "bar", "toggle", "choice", "text-cycle", "action", "info")}


def ascii_text(text):
    text = text.replace("ł", "l").replace("Ł", "L")
    return unicodedata.normalize("NFD", text).encode("ascii", "ignore").decode()


def quote(text):
    return json.dumps(ascii_text(text))


def packed(bitmap, width, height):
    assert bitmap["width"] == width and bitmap["height"] == height
    rows = bitmap["rows"]
    assert len(rows) == height
    assert all(len(row) == width and set(row) <= {"0", "1"} for row in rows)
    data = [sum((rows[y][x] == "1") << (y % 8)
                for y in range(page * 8, min(height, page * 8 + 8)))
            for page in range((height + 7) // 8) for x in range(width)]
    assert data == bitmap["pcd8544PageBytes"], "rows and packed bytes disagree"
    return data


def byte_array(name, data):
    lines = [f"static const uint8_t {name}[] = {{"]
    lines += ["  " + ", ".join(f"0x{x:02X}" for x in data[i:i + 16]) + ","
              for i in range(0, len(data), 16)]
    return "\n".join(lines + ["};"])


def compile_project(project):
    assert project["format"] == "rda5807-pcd8544-layout" and project["version"] == 2
    assert project["display"]["width"] == 84 and project["display"]["height"] == 48
    assert project["menu"]["firstLevelStyle"] == "list", "this firmware uses list navigation"
    assert 1 <= project["menu"]["visibleRows"] <= 5
    header = '''/* Generated by tools/generate_lcd_layout.py. Do not edit. */
#ifndef LCD_LAYOUT_H
#define LCD_LAYOUT_H
#include "app_config.h"
#include "radio_menu.h"
#include <stddef.h>
#include <stdint.h>

typedef struct { const uint8_t *pixels; uint32_t duration_ms; } lcd_frame_t;
typedef struct {
  const lcd_frame_t *frames;
  uint16_t frame_count;
  uint8_t width, height;
  bool loop;
} lcd_asset_t;
typedef struct {
  uint8_t x, y, width, height, graphic_count;
  const lcd_asset_t *const *graphics;
} lcd_region_t;
typedef struct {
  uint8_t width, height, spacing;
  const uint8_t *glyphs; /* Printable ASCII 32..127, packed vertical pages. */
} lcd_font_t;
typedef enum {
  LCD_ENTRY_NUMBER, LCD_ENTRY_BAR, LCD_ENTRY_TOGGLE, LCD_ENTRY_CHOICE,
  LCD_ENTRY_TEXT_CYCLE, LCD_ENTRY_ACTION, LCD_ENTRY_INFO
} lcd_entry_type_t;
typedef struct {
  radio_menu_item_t item;
  const char *label;
  lcd_entry_type_t type;
  int32_t minimum, maximum, step;
  uint8_t segments, value_count;
  const char *const *values;
  const int32_t *choice_values;
  const char *message;
} lcd_menu_entry_t;
typedef struct {
  const char *label;
  const lcd_menu_entry_t *entries;
  uint8_t entry_count;
} lcd_category_t;
typedef enum {
'''
    header += "".join(f"  LCD_REGION_{name},\n" for name in REGIONS.values())
    header += '''  LCD_REGION_COUNT
} lcd_region_id_t;
extern const lcd_region_t lcd_regions[LCD_REGION_COUNT];
extern const uint8_t lcd_home_background[504];
extern const lcd_font_t lcd_tiny_font, lcd_menu_font;
extern const lcd_category_t lcd_categories[];
extern const uint8_t lcd_category_count, lcd_visible_rows;
extern const char lcd_menu_title[];
const lcd_menu_entry_t *lcd_layout_entry(radio_menu_item_t item);
void lcd_layout_apply_defaults(radio_settings_t *settings);
#endif /* LCD_LAYOUT_H */
'''
    source = ['/* Generated by tools/generate_lcd_layout.py. Do not edit. */',
              '#include "lcd_layout.h"', '']
    background = packed(project["home"]["bitmap"], 84, 48)
    source.append(byte_array("lcd_home_background", background).replace("static ", "", 1))
    asset_names = {}
    for i, asset in enumerate(project["assets"]):
        name = f"asset_{i}"
        assert asset["id"] not in asset_names, "duplicate asset ID"
        asset_names[asset["id"]] = name
        w, h = asset["width"], asset["height"]
        assert 0 < w <= 84 and 0 < h <= 48 and asset["frames"]
        frames = []
        for j, frame in enumerate(asset["frames"]):
            frame_name = f"{name}_frame_{j}"
            source.append(byte_array(frame_name, packed(frame["bitmap"], w, h)))
            frames.append(f"  {{{frame_name}, {max(10, frame['durationMs'])}U}},")
        source += [f"static const lcd_frame_t {name}_frames[] = {{", *frames, "};",
                   f"static const lcd_asset_t {name} = "
                   f"{{{name}_frames, {len(frames)}, {w}, {h}, {str(asset['loop']).lower()}}};"]
    region_lines = []
    seen = set()
    for region in project["home"]["regions"]:
        name = REGIONS[region["name"]]
        assert name not in seen, "duplicate bound region"
        seen.add(name)
        x, y, w, h = (region[k] for k in ("x", "y", "width", "height"))
        assert w > 0 and h > 0 and x >= 0 and y >= 0 and x + w <= 84 and y + h <= 48
        graphics = [asset_names[g["assetId"]] for g in region["graphics"]]
        graphics_name = "NULL"
        if graphics:
            graphics_name = f"region_{name.lower()}_graphics"
            source.append(f"static const lcd_asset_t *const {graphics_name}[] = "
                          "{" + ", ".join("&" + g for g in graphics) + "};")
        region_lines.append(f"  [LCD_REGION_{name}] = "
                            f"{{{x}, {y}, {w}, {h}, {len(graphics)}, {graphics_name}}},")
    assert seen == set(REGIONS.values()), "missing required region"
    source += ["const lcd_region_t lcd_regions[LCD_REGION_COUNT] = {", *region_lines, "};"]
    font_map = {f["id"]: f for f in project["fonts"]}
    for name, font_id in [("lcd_tiny_font", "font-3x4"),
                          ("lcd_menu_font", project["menu"]["fontId"])]:
        font = font_map[font_id]
        w, h = font["width"], font["height"]
        assert 0 < w <= 8 and 0 < h <= 7 and 0 <= font["spacing"] <= 5
        data = []
        for code in range(32, 128):
            c = chr(code)
            glyph = font["glyphs"].get(c, font["glyphs"].get(c.upper(), font["glyphs"]["?"]))
            data += packed(glyph, w, h)
        source += [byte_array(name + "_data", data),
                   f"const lcd_font_t {name} = {{{w}, {h}, {font['spacing']}, {name}_data}};"]
    defaults = []
    category_lines = []
    used_items = set()
    for ci, category in enumerate(project["menu"]["categories"]):
        entries = []
        for ei, entry in enumerate(category["entries"]):
            item, field = ITEMS[entry["name"]]
            assert item not in used_items, "duplicate bound menu entry"
            used_items.add(item)
            options = entry["options"]
            kind = entry["type"]
            name = f"category_{ci}_entry_{ei}"
            labels = options.get("values", [])
            if kind == "toggle":
                labels = [options["offLabel"], options["onLabel"]]
            choice_values = list(range(len(labels)))
            if item == "RSSI_AVERAGE":
                choice_values = [round(float(v.split()[0]) * 1000) for v in labels]
            minimum, maximum, step = 0, 0, 1
            if kind in ("bar", "number"):
                scale = 1000 if options.get("unit") == "MHz" else 1
                minimum, maximum, step = (round(options[k] * scale) for k in ("min", "max", "step"))
                assert minimum <= maximum and step > 0
                default = round(options["defaultValue"] * scale)
                assert minimum <= default <= maximum
            elif labels:
                default_index = int(options.get("defaultIndex", options.get("defaultValue", 0)))
                assert 0 <= default_index < len(labels)
                default = choice_values[default_index]
                maximum = len(labels) - 1
            if field:
                defaults.append(f"  settings->{field} = {default};")
            if labels:
                source += [f"static const char *const {name}_labels[] = "
                           "{" + ", ".join(quote(v) for v in labels) + "};",
                           f"static const int32_t {name}_choices[] = "
                           "{" + ", ".join(map(str, choice_values)) + "};"]
            message = options.get("confirmation", options.get("value", ""))
            entries.append(f"  {{RADIO_MENU_{item}, {quote(entry['name'])}, {TYPES[kind]}, "
                           f"{minimum}, {maximum}, {step}, {options.get('segments', 0)}, {len(labels)}, "
                           f"{name + '_labels' if labels else 'NULL'}, "
                           f"{name + '_choices' if labels else 'NULL'}, {quote(message)}}},")
        if category["name"] == "System":
            # Required by the CLOCK region description, absent from exported entries.
            entries += ['  {RADIO_MENU_CLOCK, "Ustaw zegar", LCD_ENTRY_ACTION, 0, 0, 1, 0, 0, NULL, NULL, ""},',
                        '  {RADIO_MENU_CLOCK_RDS, "Zegar z RDS", LCD_ENTRY_TOGGLE, 0, 1, 1, 0, 0, NULL, NULL, ""},']
        source += [f"static const lcd_menu_entry_t category_{ci}_entries[] = {{", *entries, "};"]
        category_lines.append(f"  {{{quote(category['name'])}, category_{ci}_entries, {len(entries)}}},")
    assert used_items == {v[0] for v in ITEMS.values()}, "missing required menu entry"
    source += ["const lcd_category_t lcd_categories[] = {", *category_lines, "};",
               f"const uint8_t lcd_category_count = {len(category_lines)};",
               f"const uint8_t lcd_visible_rows = {project['menu']['visibleRows']};",
               f"const char lcd_menu_title[] = {quote(project['menu']['title'])};",
               "const lcd_menu_entry_t *lcd_layout_entry(radio_menu_item_t item) {",
               "  for (uint8_t c = 0; c < lcd_category_count; ++c)",
               "    for (uint8_t e = 0; e < lcd_categories[c].entry_count; ++e)",
               "      if (lcd_categories[c].entries[e].item == item)",
               "        return &lcd_categories[c].entries[e];", "  return NULL;", "}",
               "void lcd_layout_apply_defaults(radio_settings_t *settings) {", *defaults, "}"]
    return header, "\n".join(source) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    header, source = compile_project(json.loads(SOURCE.read_text()))
    for path, content in [(HEADER, header), (OUTPUT, source)]:
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"{path.relative_to(ROOT)} is stale; run make layout")
        else:
            path.write_text(content)
    print("LCD layout matches designer JSON." if args.check else "Generated LCD layout from designer JSON.")


if __name__ == "__main__":
    main()
